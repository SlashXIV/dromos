package com.gabrielifrim.dromos.core.domain.model

/** Ambiance visuelle choisie dans les Réglages. */
enum class MotionPreference {
    /** Tout le mouvement : fonds vivants, entrées, compteurs, tracés qui se dessinent. */
    EXPRESSIVE,

    /** Mouvement réduit au strict utile : aucun fond animé, transitions brèves. */
    CALM,
}
